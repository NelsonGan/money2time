// Emits constants/subscriptionLogos.generated.ts — the require map, brand
// metadata and country list backing the recurring-payment logo picker — from
// the PNGs that scripts/fetch-subscription-logos.mjs actually wrote.
//
//   node scripts/generate-subscription-logos.mjs
//
// Only brands with a file on disk are registered, so a catalog entry whose
// download failed is reported and skipped rather than emitting a `require` for
// a missing asset (which is a Metro-time crash, not a runtime one).
import { execFile } from 'node:child_process';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

import Jimp from 'jimp-compact';

import { isDarkMark } from './lib/darkMark.mjs';

const execFileAsync = promisify(execFile);

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');
const CATALOG = path.join(REPO_ROOT, 'scripts/data/subscription-services.json');
const ASSETS_DIR = path.join(REPO_ROOT, 'assets/subscription-logos');
const GENERATED_FILE = path.join(REPO_ROOT, 'constants/subscriptionLogos.generated.ts');

const catalog = JSON.parse(await fs.readFile(CATALOG, 'utf8'));

const countries = [];
const brands = [];
const missing = [];

for (const [countrySlug, country] of Object.entries(catalog.countries)) {
  let present = 0;
  for (const service of country.services) {
    const file = `${service.slug}.png`;
    try {
      await fs.access(path.join(ASSETS_DIR, countrySlug, file));
    } catch {
      missing.push(`${countrySlug}/${file}`);
      continue;
    }
    present += 1;
    brands.push({
      id: `${countrySlug}/${service.slug}`,
      slug: service.slug,
      name: service.name,
      file,
      category: service.category ?? 'other',
      country: countrySlug,
      countryName: country.name,
    });
  }
  if (present > 0) {
    countries.push({ slug: countrySlug, name: country.name, region: country.region ?? null });
  }
}

// "Global" leads the picker (it holds the services almost everyone recognises);
// the rest are alphabetical, matching the account-logo country sheet.
countries.sort((a, b) => {
  if (a.slug === 'global') return -1;
  if (b.slug === 'global') return 1;
  return a.name.localeCompare(b.name);
});
brands.sort((a, b) => a.id.localeCompare(b.id));

// Which tiles are dark marks on transparency; see the emitted constant. Decoded
// in small batches rather than all at once: 2000-odd 192px bitmaps held live is
// a few hundred MB for no gain, since this is disk-bound either way.
const darkMarks = [];
const DECODE_BATCH = 32;
for (let i = 0; i < brands.length; i += DECODE_BATCH) {
  const batch = await Promise.all(
    brands.slice(i, i + DECODE_BATCH).map((brand) =>
      Jimp.read(path.join(ASSETS_DIR, brand.country, brand.file))
        .then((image) => (isDarkMark(image) ? brand.id : null))
        // An unreadable tile already fails louder elsewhere (the require map
        // blows up at Metro time); here it just means "no plate", the default.
        .catch(() => null),
    ),
  );
  darkMarks.push(...batch.filter(Boolean));
}
darkMarks.sort();

const sourceLines = brands
  .map((b) => `  '${b.id}': require('../assets/subscription-logos/${b.country}/${b.file}'),`)
  .join('\n');

const brandLines = brands
  .map(
    (b) =>
      `  { id: '${b.id}', slug: '${b.slug}', name: ${JSON.stringify(b.name)}, category: '${b.category}', country: '${b.country}', countryName: ${JSON.stringify(b.countryName)} },`,
  )
  .join('\n');

const countryLines = countries
  .map(
    (c) =>
      `  { slug: '${c.slug}', name: ${JSON.stringify(c.name)}, region: ${c.region ? `'${c.region}'` : 'null'} },`,
  )
  .join('\n');

const categories = [...new Set(brands.map((b) => b.category))].sort();

const out = `// AUTO-GENERATED by scripts/generate-subscription-logos.mjs — do not edit by hand.
import type { ImageSourcePropType } from 'react-native';

export type SubscriptionLogoCategory =
${categories.map((c) => `  | '${c}'`).join('\n')};

export interface SubscriptionLogoMeta {
  /** Globally unique id: \`<countrySlug>/<brandSlug>\`. Stored on recurring_rules.logo_id. */
  id: string;
  slug: string;
  name: string;
  category: SubscriptionLogoCategory;
  country: string;
  countryName: string;
}

export interface SubscriptionLogoCountry {
  slug: string;
  name: string;
  /** ISO 3166-1 alpha-2 code, or null for the cross-border "Global" bucket. */
  region: string | null;
}

export const SUBSCRIPTION_LOGO_SOURCES: Record<string, ImageSourcePropType> = {
${sourceLines}
};

export const SUBSCRIPTION_LOGO_COUNTRIES: SubscriptionLogoCountry[] = [
${countryLines}
];

export const SUBSCRIPTION_LOGOS: SubscriptionLogoMeta[] = [
${brandLines}
];

/**
 * Ids whose art is a mostly-dark mark on transparency (Apple's glyph, Amazon's
 * wordmark). Bare on the dark surface those disappear, so SubscriptionLogo
 * draws a light plate behind them there; on the light surface they read as-is.
 * Detected at generation time by scripts/lib/darkMark.mjs.
 */
export const SUBSCRIPTION_LOGO_DARK_MARKS: readonly string[] = [
${darkMarks.map((id) => `  '${id}',`).join('\n')}
];
`;

await fs.mkdir(path.dirname(GENERATED_FILE), { recursive: true });
await fs.writeFile(GENERATED_FILE, out, 'utf8');

// CI gates on `prettier --check`, and hand-emitting 2000 prettier-shaped object
// literals is not worth it — let prettier do it so a regenerate is never the
// thing that reddens the build.
try {
  await execFileAsync('npx', ['prettier', '--write', GENERATED_FILE], { cwd: REPO_ROOT });
} catch (err) {
  console.warn(
    `prettier --write failed (run \`npm run format\` before committing): ${err.message}`,
  );
}

console.log(
  `Generated ${brands.length} subscription logos across ${countries.length} countries -> ${path.relative(REPO_ROOT, GENERATED_FILE)}`,
);
if (missing.length) {
  console.log(`\n${missing.length} catalog entries had no PNG on disk (skipped):`);
  missing.slice(0, 40).forEach((m) => console.log(`  ${m}`));
  if (missing.length > 40) console.log(`  ...and ${missing.length - 40} more`);
}
