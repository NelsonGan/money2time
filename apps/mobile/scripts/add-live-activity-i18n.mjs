const esc = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");

async function main() {
  const files = (await fs.readdir(LOCALES_DIR)).filter((f) => f.endsWith('.ts'));
  for (const file of files) {
    const locale = file.replace(/\.ts$/, '');
    const values = { ...en, ...(T[locale] ?? {}) };
    const live = { ...en.live, ...(T[locale]?.live ?? {}) };
    const full = path.join(LOCALES_DIR, file);
    let src = await fs.readFile(full, 'utf8');

    // Drop a block written by an earlier run so a copy change rewords rather
    // than colliding with itself.
    src = src.replace(/\n {4}settings_title: [\s\S]*?\n {4}live: \{[\s\S]*?\n {4}\},\n/, '\n');

    const anchor = src.match(/^(\s*)budget_unbudgeted:.*$/m);
    if (!anchor) {
      console.warn(`skip ${file}: no widgets.budget_unbudgeted anchor`);
      continue;
    }

    const lines = [];
    for (const key of FLAT_KEYS) lines.push(`    ${key}: '${esc(values[key])}',`);
    lines.push('    live: {');
    for (const key of LIVE_KEYS) lines.push(`      ${key}: '${esc(live[key])}',`);
    lines.push('    },');

    const at = anchor.index + anchor[0].length;
    await fs.writeFile(full, `${src.slice(0, at)}\n${lines.join('\n')}${src.slice(at)}`, 'utf8');
    console.log(`patched ${file}`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
