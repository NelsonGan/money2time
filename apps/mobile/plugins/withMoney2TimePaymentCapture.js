function patchMainApplication(androidRoot) {
  const filePath = path.join(androidRoot, 'app/src/main/java', PACKAGE_PATH, 'MainApplication.kt');
  if (!fs.existsSync(filePath)) {
    throw new Error(
      'withMoney2TimePaymentCapture: expected MainApplication.kt to register the module.',
    );
  }
  let source = fs.readFileSync(filePath, 'utf8');
  if (source.includes('PaymentCapturePackage')) return;
  source = source.replace(
    /package com\.nelsongan\.money2time\n/,
    `package com.nelsongan.money2time\n\nimport ${CAPTURE_PACKAGE}.PaymentCapturePackage\n`,
  );
  const patched = source.replace(
    /(PackageList\(this\)\.packages\s*)/,
    '$1\n          .also { packages -> packages.add(PaymentCapturePackage()) }',
  );
  if (patched === source) {
    throw new Error(
      'withMoney2TimePaymentCapture: could not find PackageList in MainApplication.kt.',
    );
  }
  fs.writeFileSync(filePath, patched);
}

function withPaymentCaptureSources(config) {
  return withDangerousMod(config, [
    'android',
    (cfg) => {
      const androidRoot = cfg.modRequest.platformProjectRoot;
      const sourceRoot = path.join(
        androidRoot,
        'app/src/main/java',
        PACKAGE_PATH,
        'paymentcapture',
      );
      writeFileIfChanged(path.join(sourceRoot, 'PaymentCaptureStore.kt'), STORE_SOURCE);
      writeFileIfChanged(path.join(sourceRoot, 'PaymentCaptureListener.kt'), LISTENER_SOURCE);
      writeFileIfChanged(path.join(sourceRoot, 'PaymentCaptureModule.kt'), MODULE_SOURCE);
      writeFileIfChanged(path.join(sourceRoot, 'PaymentCapturePackage.kt'), PACKAGE_SOURCE);
      patchMainApplication(androidRoot);
      return cfg;
    },
  ]);
}

function withPaymentCaptureManifest(config) {
  return withAndroidManifest(config, (cfg) => {
    const manifest = cfg.modResults.manifest;
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);

    app.service = (app.service ?? []).filter(
      (service) => service.$?.['android:name'] !== SERVICE_NAME,
    );
    app.service.push({
      $: {
        'android:name': SERVICE_NAME,
        'android:exported': 'true',
        'android:permission': 'android.permission.BIND_NOTIFICATION_LISTENER_SERVICE',
      },
      'intent-filter': [
        {
          action: [
            { $: { 'android:name': 'android.service.notification.NotificationListenerService' } },
          ],
        },
      ],
      'meta-data': [
        // Android 12+ lets the user narrow what a listener receives; ongoing
        // notifications (media, navigation, downloads) are never alerts.
        {
          $: {
            'android:name': 'android.service.notification.default_filter_types',
            'android:value': 'conversations|alerting|silent',
          },
        },
        {
          $: {
            'android:name': 'android.service.notification.disabled_filter_types',
            'android:value': 'ongoing',
          },
        },
      ],
    });

    // Suggested apps, so the picker can tell which are installed.
    const packages = paymentAppPackages(cfg.modRequest.projectRoot);
    const ours = new Set(packages);
    manifest.queries = (manifest.queries ?? [])
      .map((query) => ({
        ...query,
        package: (query.package ?? []).filter((entry) => !ours.has(entry.$?.['android:name'])),
      }))
      .filter((query) =>
        Object.keys(query).some((key) => key !== 'package' || query.package.length > 0),
      );
    manifest.queries.push({
      package: packages.map((name) => ({ $: { 'android:name': name } })),
    });
    return cfg;
  });
}

