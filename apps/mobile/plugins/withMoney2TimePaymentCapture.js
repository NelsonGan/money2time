function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function writeFileIfChanged(filePath, contents) {
  ensureDir(path.dirname(filePath));
  if (fs.existsSync(filePath) && fs.readFileSync(filePath, 'utf8') === contents) return;
  fs.writeFileSync(filePath, contents);
}

/**
 * Package ids of the suggested payment apps. Read out of the TypeScript catalog
 * rather than duplicated, so adding an app there is the whole job; a test
 * checks this matches PAYMENT_APPS.
 */
function paymentAppPackages(projectRoot) {
  const source = fs.readFileSync(path.join(projectRoot, PAYMENT_APPS_SOURCE), 'utf8');
  const packages = new Set();
  for (const match of source.matchAll(/\bpackage:\s*'([A-Za-z0-9_.]+)'/g)) {
    packages.add(match[1]);
  }
  return [...packages].sort();
}

