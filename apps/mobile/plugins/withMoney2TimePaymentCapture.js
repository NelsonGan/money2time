/**
 * Android payment alerts: a NotificationListenerService that copies the text of
 * payment notifications from the banking and wallet apps the user picked into
 * the app's files directory, where the JS drain (PaymentAlertSync) parses and
 * queues them for user review. Design: "Notification review" in the repository README.
 *
 * What the listener does, and deliberately does not do:
 *
 * - **It reads only the apps the user chose.** `config.json`, written by the
 *   JS side, lists them; everything else is dropped in memory. With no config
 *   (or capture off) nothing is kept. The one other thing it notes is which
 *   apps post notifications at all (package and label, never content), so the
 *   setup screen can offer "Recently active" apps.
 * - **It does no parsing and logs nothing.** It writes raw text, one file per
 *   alert, `<millis>-<uuid>.json` written as `.part` and renamed, so a file the
 *   drain can see is always complete and the folder listing is the queue
 *   (features/autoLog/lib/captureQueue.ts reads it). Parsing, binding,
 *   categories and de-duplication live in TypeScript, where they are tested.
 * - **It never starts JS.** The drain runs the next time the app is open; when
 *   it already is, the module emits `Money2TimePaymentCaptureQueued` so the
 *   payment appears at once.
 * - **The setup screen's test alert** is money2time's own notification tagged
 *   `m2t-payment-alert-test`; it is captured with `"test": true` and only ever
 *   previewed.
 *
 * Play policy: notification access needs the prominent disclosure the setup
 * screen shows before sending the user to the system toggle, and a Play
 * Console declaration. Sideloaded builds on Android 13+ get "restricted
 * settings"; the setup screen explains the workaround.
 *
 * Package visibility: the suggested apps are declared in a `<queries>` block
 * built from features/autoLog/lib/paymentApps.ts, so the picker can show the
 * installed ones without QUERY_ALL_PACKAGES.
 */

