/**
 * Regenerates src/lib/icons.generated.ts from the icon PNGs in media/.
 *
 * Both sets are copied over from the app (apps/mobile):
 *   media/clay-icons/<set>/<name>.png   <- assets/clay-icons
 *   media/category-icons/<name>.png     <- assets/icon-packs/default
 *
 * Run after syncing new artwork:  node scripts/generate-icon-catalog.mjs
 * and then publish it:            node scripts/upload-media.mjs
 */
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const MEDIA_DIR = new URL("../media/", import.meta.url).pathname;

function walk(dir, prefix = "") {
  return readdirSync(dir)
    .flatMap((entry) => {
      const full = join(dir, entry);
      if (statSync(full).isDirectory()) return walk(full, `${prefix}${entry}/`);
      return entry.endsWith(".png") ? [`${prefix}${entry.replace(/\.png$/, "")}`] : [];
    })
    .sort();
}

const clay = walk(join(MEDIA_DIR, "clay-icons"));
const category = walk(join(MEDIA_DIR, "category-icons"));

const list = (items) => items.map((id) => `  "${id}",`).join("\n");

writeFileSync(
  new URL("../src/lib/icons.generated.ts", import.meta.url),
  `// AUTO-GENERATED by scripts/generate-icon-catalog.mjs — do not edit by hand.
// Artwork lives in media/clay-icons and media/category-icons, copied from the
// app (apps/mobile).

/** Clay icons, keyed \`<set>/<name>\`. */
export const CLAY_ICONS = [
${list(clay)}
] as const;

export type ClayIconName = (typeof CLAY_ICONS)[number];

/** Category icons from the app's default icon pack. */
export const CATEGORY_ICONS = [
${list(category)}
] as const;

export type CategoryIconName = (typeof CATEGORY_ICONS)[number];
`,
);

console.log(`clay: ${clay.length}, category: ${category.length}`);
