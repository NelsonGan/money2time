// Regenerates src/lib/energy.generated.ts from GlobalPetrolPrices.
//
//   node scripts/generate-energy-data.mjs
//
// Petrol and household electricity are two of the few everyday prices
// published on one methodology for every market here: the same grade of fuel
// and the same kind of residential tariff, gathered by one publisher on one
// date. GlobalPetrolPrices asks for attribution, which the page carries.
import { execFileSync } from "node:child_process";
import fs from "node:fs";

