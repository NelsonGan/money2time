// Regenerates src/lib/bigmac.generated.ts from The Economist's published index.
//
//   node scripts/generate-bigmac-data.mjs
//
// The Big Mac index is the only consumer price series that is genuinely
// comparable across every market this site serves: the same product, priced by
// McDonald's, gathered on one date by one publisher. Numbeo would cover a
// wider basket but its prices are crowd-sourced and its site is not reachable
// from this build, so the page uses what can be verified at source instead.
import fs from "node:fs";

const SOURCE =
  "https://raw.githubusercontent.com/TheEconomist/big-mac-data/master/output-data/big-mac-full-index.csv";

/** Market code by ISO 3166-1 alpha-3, for every country the site serves. */
const MARKET_BY_ISO3 = {
  AUS: "AU",
  BRA: "BR",
  CAN: "CA",
  CHN: "CN",
  DNK: "DK",
  GBR: "GB",
  IDN: "ID",
  IND: "IN",
  JPN: "JP",
  KOR: "KR",
  MYS: "MY",
  NOR: "NO",
  NZL: "NZ",
  PHL: "PH",
  POL: "PL",
  SGP: "SG",
  SWE: "SE",
  THA: "TH",
  TUR: "TR",
  UKR: "UA",
  USA: "US",
  VNM: "VN",
  ZAF: "ZA",
};

/**
 * The Economist prices the euro area as one entity rather than country by
 * country, so its members share that figure.
 */
const EURO_AREA = ["DE", "ES", "FR", "IT", "NL"];

/**
 * Russia has had no Big Mac since McDonald's left in 2022, and The Economist
 * dropped it from the index. The page shows the gap rather than a substitute.
 */
const NO_BIG_MAC = ["RU"];

function parseCsv(text) {
  const [header, ...lines] = text.trim().split("\n");
  const columns = header.split(",");
  return lines.map((line) => {
    const cells = line.split(",");
    return Object.fromEntries(columns.map((column, i) => [column, cells[i]]));
  });
}

const rows = parseCsv(await (await fetch(SOURCE)).text());
const date = rows.reduce((latest, row) => (row.date > latest ? row.date : latest), "");
const latest = rows.filter((row) => row.date === date && row.iso_a3 in MARKET_BY_ISO3);

const missing = Object.values(MARKET_BY_ISO3).filter(
  (code) => !latest.some((row) => MARKET_BY_ISO3[row.iso_a3] === code),
);
if (missing.length > 0) {
  throw new Error(`No ${date} Big Mac price for: ${missing.join(", ")}`);
}

const euro = rows.find((row) => row.date === date && row.iso_a3 === "EUZ");
if (!euro) {
  throw new Error(`No ${date} euro-area Big Mac price`);
}

const entries = [
  ...latest.map((row) => ({
    code: MARKET_BY_ISO3[row.iso_a3],
    price: Number(row.local_price),
    /** Local currency units per US dollar, on the same date. */
    usdRate: Number(row.dollar_ex),
  })),
  ...EURO_AREA.map((code) => ({
    code,
    price: Number(euro.local_price),
    usdRate: Number(euro.dollar_ex),
  })),
].sort((a, b) => a.code.localeCompare(b.code));

const file = `// AUTO-GENERATED by scripts/generate-bigmac-data.mjs — do not edit by hand.
//
// The Economist's Big Mac index, which prices one identical product across
// every market on a single date. Big Mac prices come from McDonald's and from
// reporting around the world; exchange rates are from Refinitiv Datastream.
// https://github.com/TheEconomist/big-mac-data
import type { CountryCode } from "@/lib/countries";

/** The survey date these prices were gathered on. */
export const BIG_MAC_DATE = "${date}";

export const BIG_MAC_SOURCE = "The Economist, Big Mac index";
export const BIG_MAC_SOURCE_URL =
  "https://github.com/TheEconomist/big-mac-data";

export type BigMacPrice = {
  /** In the market's own currency, as published. */
  price: number;
  /** Local currency units per US dollar on the survey date. */
  usdRate: number;
};

/** Absent where the country has no Big Mac to price. */
export const BIG_MAC: Partial<Record<CountryCode, BigMacPrice>> = {
${entries
  .map(
    ({ code, price, usdRate }) =>
      `  ${code}: { price: ${price}, usdRate: ${usdRate} },`,
  )
  .join("\n")}
};
`;

fs.writeFileSync("src/lib/bigmac.generated.ts", file);
console.log(
  `Wrote ${entries.length} Big Mac prices for ${date} (${EURO_AREA.length} from the euro-area row, none for ${NO_BIG_MAC.join(", ")}).`,
);
