-- Cloud Backup & Web Dashboard (money2time-d1-cloud-backup).
--
-- Apply with:
--   npx wrangler d1 execute money2time-d1-cloud-backup --remote --file=../../d1/cloud-backup/schema.sql
-- (run from apps/cloudflare/workers/cloud-backup; drop --remote for local dev).
--
-- There are no accounts. A backup lives in a vault identified by its
-- end-to-end encryption key: the phone derives the vault id and a vault secret
-- from the key (HMACs; see the app's services/cloudBackupCrypto.ts), and this
-- database stores only a hash of the secret. Whoever holds the key (the phone,
-- a phone it handed the key to by QR code, or the recovery key) can reach the
-- vault; nobody else can, and the server cannot read what is in it. Every
-- table holds metadata only; the encrypted backup itself is in R2.

-- A vault: one end-to-end encrypted backup and the phones and browsers that
-- can reach it.
create table if not exists vault (
  id text not null primary key,
  secret_hash text not null,
  -- The one phone allowed to upload. Two phones writing would overwrite each
  -- other, so another phone takes over only by an explicit transfer.
  primary_device_id text,
  created_at integer not null,
  last_seen_at integer not null
);

-- A phone using the vault. `id` is generated by the app once per install and
-- kept in its keychain.
create table if not exists device (
  vault_id text not null references vault (id) on delete cascade,
  id text not null,
  platform text not null,
  name text,
  app_version text,
  -- The RevenueCat App User ID the app runs with, so the web dashboard can
  -- tell whether this vault's owner has Pro.
  app_user_id text,
  created_at integer not null,
  last_seen_at integer not null,
  primary key (vault_id, id)
);

-- The vault's backup. Only the latest is kept: an upload replaces the row and
-- deletes the previous R2 object.
create table if not exists backup (
  vault_id text not null primary key references vault (id) on delete cascade,
  id text not null,
  device_id text not null,
  r2_key text not null,
  created_at integer not null,
  size integer not null,
  sha256 text not null,
  schema_version integer not null,
  app_version text,
  exported_at text
);

-- A QR-code link in progress, WhatsApp-style. A browser (or a new phone)
-- generates a key pair and shows its public half in a QR code; a phone holding
-- the key scans it and posts the backup key wrapped for that public key. The
-- server only relays the wrapped key and cannot unwrap it. Rows live for two
-- minutes; the daily cron removes old ones.
create table if not exists link_request (
  id text not null primary key,
  kind text not null,
  poll_token_hash text not null,
  public_key text not null,
  name text,
  ip_hash text,
  vault_id text,
  status text not null,
  phone_public_key text,
  wrapped_key text,
  wrapped_iv text,
  approved_by_device text,
  web_token text,
  created_at integer not null,
  expires_at integer not null
);
create index if not exists link_request_ip_idx on link_request (ip_hash, created_at);

-- A browser linked by scanning: the web dashboard's only credential.
-- Revocable from the phone; the token itself is stored hashed.
create table if not exists web_session (
  id text not null primary key,
  vault_id text not null references vault (id) on delete cascade,
  token_hash text not null unique,
  name text,
  created_at integer not null,
  last_seen_at integer not null,
  revoked_at integer
);
create index if not exists web_session_vault_idx on web_session (vault_id);

-- Short-lived RevenueCat Pro/free answers, keyed by App User ID (1h Pro,
-- 60s free), so a dashboard visit does not wait on RevenueCat each time.
create table if not exists entitlement_cache (
  app_user_id text not null primary key,
  is_pro integer not null,
  expires_at integer not null
);

-- Per-address counters for the endpoints anyone can call (creating a vault,
-- starting a QR link), in fixed windows.
create table if not exists rate_limit (
  key text not null primary key,
  window_start integer not null,
  count integer not null
);
