-- Cloud Backup & Web Dashboard (money2time-d1-cloud-backup).
--
-- Apply with:
--   npx wrangler d1 execute money2time-d1-cloud-backup --remote --file=../../d1/cloud-backup/schema.sql
-- (run from apps/cloudflare/workers/cloud-backup; drop --remote for local dev).
--
-- The first five tables are Better Auth's own, generated from better-auth
-- 1.7.11 with the email-OTP plugin and database rate limiting; keep them in
-- step with `getMigrations` when Better Auth is upgraded. The rest hold only
-- metadata: the backup itself lives in the private R2 bucket.

create table if not exists "user" ("id" text not null primary key, "name" text not null, "email" text not null unique, "emailVerified" integer not null, "image" text, "createdAt" date not null, "updatedAt" date not null);

create table if not exists "session" ("id" text not null primary key, "expiresAt" date not null, "token" text not null unique, "createdAt" date not null, "updatedAt" date not null, "ipAddress" text, "userAgent" text, "userId" text not null references "user" ("id") on delete cascade);

create table if not exists "account" ("id" text not null primary key, "accountId" text not null, "providerId" text not null, "userId" text not null references "user" ("id") on delete cascade, "accessToken" text, "refreshToken" text, "idToken" text, "accessTokenExpiresAt" date, "refreshTokenExpiresAt" date, "scope" text, "password" text, "createdAt" date not null, "updatedAt" date not null);

create table if not exists "verification" ("id" text not null primary key, "identifier" text not null, "value" text not null, "expiresAt" date not null, "createdAt" date not null, "updatedAt" date not null);

create table if not exists "rateLimit" ("id" text not null primary key, "key" text not null unique, "count" integer not null, "lastRequest" bigint not null);

create index if not exists "session_userId_idx" on "session" ("userId");
create index if not exists "account_userId_idx" on "account" ("userId");
create index if not exists "verification_identifier_idx" on "verification" ("identifier");

-- A phone signed in to the account. `id` is generated by the app once per
-- install and kept in secure storage, so the same phone signing in to two
-- accounts is two rows.
create table if not exists device (
  user_id text not null references "user" ("id") on delete cascade,
  id text not null,
  platform text not null,
  name text,
  app_version text,
  -- The RevenueCat App User ID the app runs with, so the account's Pro
  -- entitlement can be checked for the web dashboard.
  app_user_id text,
  created_at integer not null,
  last_seen_at integer not null,
  primary key (user_id, id)
);

-- The one device allowed to upload. Two phones writing the same backup would
-- overwrite each other, so a second phone has to take this over explicitly.
create table if not exists primary_device (
  user_id text not null primary key references "user" ("id") on delete cascade,
  device_id text not null,
  assigned_at integer not null
);

-- Short-lived RevenueCat Pro/free answers, keyed by App User ID (1h Pro,
-- 60s free), so a dashboard visit does not wait on RevenueCat each time.
create table if not exists entitlement_cache (
  app_user_id text not null primary key,
  is_pro integer not null,
  expires_at integer not null
);

-- The account's backup. Only the latest is kept: an upload replaces the row
-- and deletes the previous R2 object.
create table if not exists backup (
  user_id text not null primary key references "user" ("id") on delete cascade,
  id text not null,
  device_id text not null,
  r2_key text not null,
  created_at integer not null,
  size integer not null,
  sha256 text not null,
  schema_version integer not null,
  app_version text,
  exported_at text
);

-- End-to-end encryption. Backups are encrypted on the phone with a key the
-- server never sees. This is only an HMAC fingerprint of that key, so a phone
-- can tell whether the key it holds is the account's current one.
create table if not exists account_key (
  user_id text not null primary key references "user" ("id") on delete cascade,
  key_check text not null,
  created_at integer not null
);

-- A QR-code link in progress, WhatsApp-style. A browser (or a new phone)
-- generates a key pair and shows its public half in a QR code; a signed-in
-- phone scans it and posts the backup key wrapped for that public key. The
-- server only relays the wrapped key and cannot unwrap it. Rows live for two
-- minutes; the daily cron removes old ones.
create table if not exists link_request (
  id text not null primary key,
  kind text not null,
  poll_token_hash text not null,
  public_key text not null,
  name text,
  ip_hash text,
  user_id text,
  status text not null,
  phone_public_key text,
  wrapped_key text,
  wrapped_iv text,
  approved_by_device text,
  web_token text,
  created_at integer not null,
  expires_at integer not null
);
create index if not exists link_request_ip_idx on link_request (ip_hash, created_at);

-- A browser linked by scanning: the web dashboard's only credential. Revocable
-- from the phone; the token itself is stored hashed.
create table if not exists web_session (
  id text not null primary key,
  user_id text not null references "user" ("id") on delete cascade,
  token_hash text not null unique,
  name text,
  created_at integer not null,
  last_seen_at integer not null,
  revoked_at integer
);
create index if not exists web_session_user_idx on web_session (user_id);
