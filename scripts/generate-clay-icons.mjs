// Generates the clay UI icon registry from the PNGs under assets/clay-icons/.
// Emits constants/clayIcons.generated.ts.
//
// Layout is the source of truth:
//
//   assets/clay-icons/<set>/<icon>.png   ->   '<set>/<icon>'
//
// These are the app's *chrome* illustrations (bottom tabs, Settings tiles,
// insight-type art, entry affordances, status and empty-state art) and are a
// separate namespace from the category packs under assets/icon-packs/, which
// the user picks from. Nothing here is user-selectable, so the ids only ever
// appear in source and never in a DB row.
//
// Re-run after the icon set changes:
//   node scripts/generate-clay-icons.mjs
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');
const ICONS_DIR = path.join(REPO_ROOT, 'assets/clay-icons');
const GENERATED_FILE = path.join(REPO_ROOT, 'constants/clayIcons.generated.ts');

async function readDirs(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  return entries
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith('.'))
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b));
}

async function main() {
  const setNames = await readDirs(ICONS_DIR);
  if (setNames.length === 0) throw new Error(`No clay icon sets found under ${ICONS_DIR}`);

  const icons = [];
  for (const setName of setNames) {
    const files = (await fs.readdir(path.join(ICONS_DIR, setName)))
      .filter((file) => file.toLowerCase().endsWith('.png'))
      .sort((a, b) => a.localeCompare(b));
    for (const file of files) {
      const name = file.slice(0, file.length - '.png'.length);
      icons.push({
        id: `${setName}/${name}`,
        require: `../assets/clay-icons/${setName}/${file}`,
      });
    }
  }

  const sourceLines = icons.map((icon) => `  '${icon.id}': require('${icon.require}'),`).join('\n');

  const out = `// AUTO-GENERATED by scripts/generate-clay-icons.mjs — do not edit by hand.
// Source layout: assets/clay-icons/<set>/<icon>.png
import type { ImageSourcePropType } from 'react-native';

export const CLAY_ICON_SOURCES = {
${sourceLines}
} satisfies Record<string, ImageSourcePropType>;

export type ClayIconName = keyof typeof CLAY_ICON_SOURCES;
`;

  await fs.writeFile(GENERATED_FILE, out, 'utf8');
  console.log(
    `Generated ${icons.length} clay icons across ${setNames.length} set(s) → ` +
      `${path.relative(REPO_ROOT, GENERATED_FILE)}`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
