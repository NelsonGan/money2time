// Generates bundled account-logo assets + registry from the screenshots-creator
// manifest. Copies every PNG into assets/account-logos/<country>/<slug>.png and
// emits constants/accountLogos.generated.ts (require map + metadata + countries).
//
// Re-run after the source logo set changes:
//   node scripts/generate-account-logos.mjs
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');
const SOURCE_DIR = path.resolve(REPO_ROOT, '../money2time-screenshots-creator/public/logos');
const ASSETS_DIR = path.join(REPO_ROOT, 'assets/account-logos');
const GENERATED_FILE = path.join(REPO_ROOT, 'constants/accountLogos.generated.ts');

async function main() {
  const manifestRaw = await fs.readFile(path.join(SOURCE_DIR, 'manifest.json'), 'utf8');
  const manifest = JSON.parse(manifestRaw);
  const countryEntries = Object.entries(manifest.countries);

  await fs.rm(ASSETS_DIR, { recursive: true, force: true });
  await fs.mkdir(ASSETS_DIR, { recursive: true });

  const countries = [];
  const brands = [];
  const missing = [];

  for (const [countrySlug, country] of countryEntries) {
    const destCountryDir = path.join(ASSETS_DIR, countrySlug);
    await fs.mkdir(destCountryDir, { recursive: true });

    let copiedForCountry = 0;
    for (const brand of country.brands) {
      const src = path.join(SOURCE_DIR, countrySlug, brand.file);
      const dest = path.join(destCountryDir, brand.file);
      // Tolerate manifest entries whose PNG isn't present locally yet — skip and
      // report rather than crashing, so the build stays consistent with the
      // files actually on disk.
      try {
        await fs.copyFile(src, dest);
      } catch (err) {
        if (err?.code === 'ENOENT') {
          missing.push(`${countrySlug}/${brand.file}`);
          continue;
        }
        throw err;
      }
      copiedForCountry += 1;
      brands.push({
        id: `${countrySlug}/${brand.slug}`,
        slug: brand.slug,
        name: brand.name,
        file: brand.file,
        country: countrySlug,
        countryName: country.name,
      });
    }

    // Drop empty country dirs and keep a country in the list only if it has logos.
    if (copiedForCountry === 0) {
      await fs.rm(destCountryDir, { recursive: true, force: true });
    } else {
      countries.push({ slug: countrySlug, name: country.name });
    }
  }

  countries.sort((a, b) => a.name.localeCompare(b.name));
  brands.sort((a, b) => a.id.localeCompare(b.id));

  const sourceLines = brands
    .map((b) => `  '${b.id}': require('../assets/account-logos/${b.country}/${b.file}'),`)
    .join('\n');

  const brandLines = brands
    .map(
      (b) =>
        `  { id: '${b.id}', slug: '${b.slug}', name: ${JSON.stringify(b.name)}, country: '${b.country}', countryName: ${JSON.stringify(b.countryName)} },`,
    )
    .join('\n');

  const countryLines = countries
    .map((c) => `  { slug: '${c.slug}', name: ${JSON.stringify(c.name)} },`)
    .join('\n');

  const out = `// AUTO-GENERATED by scripts/generate-account-logos.mjs — do not edit by hand.
import type { ImageSourcePropType } from 'react-native';

export interface AccountLogoMeta {
  /** Globally unique id: \`<countrySlug>/<brandSlug>\`. Stored on accounts.logo_id. */
  id: string;
  slug: string;
  name: string;
  country: string;
  countryName: string;
}

export interface AccountLogoCountry {
  slug: string;
  name: string;
}

export const ACCOUNT_LOGO_SOURCES: Record<string, ImageSourcePropType> = {
${sourceLines}
};

export const ACCOUNT_LOGO_COUNTRIES: AccountLogoCountry[] = [
${countryLines}
];

export const ACCOUNT_LOGOS: AccountLogoMeta[] = [
${brandLines}
];
`;

  await fs.mkdir(path.dirname(GENERATED_FILE), { recursive: true });
  await fs.writeFile(GENERATED_FILE, out, 'utf8');

  console.log(
    `Generated ${brands.length} logos across ${countries.length} countries → ${path.relative(REPO_ROOT, GENERATED_FILE)}`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
