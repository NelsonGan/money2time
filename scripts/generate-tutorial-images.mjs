// Generates the tutorial screenshot registry from the PNGs under
// assets/tutorials/. Emits features/tutorials/content/images.generated.ts.
//
//   assets/tutorials/<name>.png   ->   '<name>'
//
// Metro needs a literal path inside require(), so a tutorial step cannot build
// its own require from the image name in the catalog. This registry is that
// indirection: the catalog names an image, `tutorialImage()` resolves it, and a
// name with no file resolves to null and renders an empty frame instead of
// crashing the screen.
//
// The art itself is produced by scripts/annotate-tutorials.mjs.
//
// Re-run after adding or removing a screenshot:
//   node scripts/generate-tutorial-images.mjs
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');
const IMAGES_DIR = path.join(REPO_ROOT, 'assets/tutorials');
const GENERATED_FILE = path.join(REPO_ROOT, 'features/tutorials/content/images.generated.ts');

async function main() {
  await fs.mkdir(IMAGES_DIR, { recursive: true });
  const names = (await fs.readdir(IMAGES_DIR))
    .filter((file) => file.toLowerCase().endsWith('.png'))
    .map((file) => file.slice(0, -'.png'.length))
    .sort((a, b) => a.localeCompare(b));

  const lines = names
    .map((name) => `  '${name}': require('~/assets/tutorials/${name}.png'),`)
    .join('\n');

  const out = `// AUTO-GENERATED by scripts/generate-tutorial-images.mjs — do not edit by hand.
// Source layout: assets/tutorials/<name>.png
import type { ImageSourcePropType } from 'react-native';

export const TUTORIAL_IMAGE_SOURCES: Record<string, ImageSourcePropType> = {
${lines}
};
`;

  await fs.writeFile(GENERATED_FILE, out, 'utf8');
  console.warn(
    `Wrote ${names.length} tutorial image(s) to ${path.relative(REPO_ROOT, GENERATED_FILE)}`,
  );
}

await main();
