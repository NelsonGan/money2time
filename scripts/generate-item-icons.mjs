// Generates the bundled item-icon registry from the PNGs in assets/items/.
// Emits constants/itemIcons.generated.ts (require map + metadata).
//
// Re-run after the icon set changes:
//   node scripts/generate-item-icons.mjs
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');
const ICONS_DIR = path.join(REPO_ROOT, 'assets/items');
const GENERATED_FILE = path.join(REPO_ROOT, 'constants/itemIcons.generated.ts');
const BATCHES_FILE = path.join(REPO_ROOT, 'scripts/data/item-icon-batches.json');
const GROUPS_FILE = path.join(REPO_ROOT, 'scripts/data/item-icon-groups.json');
const SLUG_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

/** `air-fryer` → `Air Fryer`. */
function titleCase(slug) {
  return slug
    .split('-')
    .filter(Boolean)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');
}

async function main() {
  const batches = JSON.parse(await fs.readFile(BATCHES_FILE, 'utf8'));
  const groupConfig = JSON.parse(await fs.readFile(GROUPS_FILE, 'utf8'));
  const displayGroups = new Set(groupConfig.order);
  if (groupConfig.order.some((group) => !SLUG_PATTERN.test(group))) {
    throw new Error('Display groups must be lowercase hyphenated slugs');
  }
  if (displayGroups.size !== groupConfig.order.length) {
    throw new Error('Display group order contains duplicates');
  }
  if (!displayGroups.has('other')) throw new Error('Display group order must include other');

  const groupById = new Map();

  for (const [group, ids] of Object.entries(groupConfig.legacyGroups)) {
    if (!displayGroups.has(group)) throw new Error(`Unknown legacy display group ${group}`);
    for (const id of ids) {
      if (!SLUG_PATTERN.test(id)) throw new Error(`Invalid item icon id ${id}`);
      if (groupById.has(id)) throw new Error(`Duplicate configured item icon id ${id}`);
      groupById.set(id, group);
    }
  }
  const batchNames = new Set();
  for (const batch of batches) {
    if (!SLUG_PATTERN.test(batch.group)) throw new Error(`Invalid batch id ${batch.group}`);
    if (batchNames.has(batch.group)) throw new Error(`Duplicate batch id ${batch.group}`);
    batchNames.add(batch.group);
    const group = groupConfig.batchGroups[batch.group];
    if (!group) throw new Error(`No display group configured for batch ${batch.group}`);
    if (!displayGroups.has(group)) {
      throw new Error(`Unknown display group ${group} configured for batch ${batch.group}`);
    }
    for (const id of batch.items) {
      if (!SLUG_PATTERN.test(id)) throw new Error(`Invalid item icon id ${id}`);
      if (groupById.has(id)) throw new Error(`Duplicate configured item icon id ${id}`);
      groupById.set(id, group);
    }
  }
  for (const batchId of Object.keys(groupConfig.batchGroups)) {
    if (!batchNames.has(batchId))
      throw new Error(`Display group configured for missing batch ${batchId}`);
  }
  for (const [id, group] of Object.entries(groupConfig.overrides)) {
    if (!SLUG_PATTERN.test(id)) throw new Error(`Invalid item icon override id ${id}`);
    if (!displayGroups.has(group)) throw new Error(`Unknown override display group ${group}`);
    groupById.set(id, group);
  }

  const entries = await fs.readdir(ICONS_DIR);
  const pngIds = new Set(
    entries
      .filter((file) => file.toLowerCase().endsWith('.png'))
      .map((file) => file.slice(0, file.length - '.png'.length)),
  );
  for (const id of pngIds) {
    if (!SLUG_PATTERN.test(id)) throw new Error(`Invalid item icon filename ${id}.png`);
  }
  for (const id of groupById.keys()) {
    if (!pngIds.has(id)) throw new Error(`Configured item icon is missing assets/items/${id}.png`);
  }
  for (const id of Object.keys(groupConfig.names ?? {})) {
    if (!pngIds.has(id)) throw new Error(`Named item icon is missing assets/items/${id}.png`);
  }

  const icons = entries
    .filter((file) => file.toLowerCase().endsWith('.png'))
    .map((file) => {
      const slug = file.slice(0, file.length - '.png'.length);
      const group = groupById.get(slug);
      if (!group) throw new Error(`No display group configured for item icon ${slug}`);
      return {
        id: slug,
        file,
        name: groupConfig.names?.[slug] ?? titleCase(slug),
        group,
      };
    })
    .sort((a, b) => a.id.localeCompare(b.id));

  const sourceLines = icons
    .map((icon) => `  '${icon.id}': require('../assets/items/${icon.file}'),`)
    .join('\n');

  const metaLines = icons
    .map(
      (icon) =>
        `  { id: '${icon.id}', name: ${JSON.stringify(icon.name)}, group: '${icon.group}' },`,
    )
    .join('\n');

  const out = `// AUTO-GENERATED by scripts/generate-item-icons.mjs — do not edit by hand.
import type { ImageSourcePropType } from 'react-native';

export interface ItemIconMeta {
  /** Stable id (the icon filename without extension). Stored on items.icon_id. */
  id: string;
  name: string;
  /** Emoji-style section used by the item picker. */
  group: ItemIconGroup;
}

export type ItemIconGroup = ${groupConfig.order.map((group) => `'${group}'`).join(' | ')};

export const ITEM_ICON_GROUP_ORDER: readonly ItemIconGroup[] = [
${groupConfig.order.map((group) => `  '${group}',`).join('\n')}
];

export const ITEM_ICON_SOURCES: Record<string, ImageSourcePropType> = {
${sourceLines}
};

export const ITEM_ICONS: ItemIconMeta[] = [
${metaLines}
];
`;

  await fs.mkdir(path.dirname(GENERATED_FILE), { recursive: true });
  await fs.writeFile(GENERATED_FILE, out, 'utf8');

  console.log(`Generated ${icons.length} item icons → ${path.relative(REPO_ROOT, GENERATED_FILE)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
